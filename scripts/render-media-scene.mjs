import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {compileScene} from './media-scene.mjs';
import {mediaRuntimeHash} from './media-runtime.mjs';
import {mediaRecipe} from './media-recipes/index.mjs';
import {sceneCommands} from '../prototype/media-scene.mjs';
const selector=process.argv.indexOf('--scene');
const recipe=mediaRecipe(selector<0?'mouse':process.argv[selector+1]);
const playback=compileScene(recipe),{payload,frameMs}=playback;
const output=path.resolve('.release/media/images/pixel-cat-'+recipe.id+'.gif');
const frames=payload.frames.map(state=>sceneCommands(payload,state));
const result=spawnSync(process.env.PYTHON||'python',['scripts/encode-readme-gif.py',output],{input:JSON.stringify({width:recipe.width,height:recipe.height,frameMs,frames}),encoding:'utf8',maxBuffer:1024*1024});
if(result.error)throw result.error;
if(result.status!==0)throw Error(result.stderr);
const hash=value=>crypto.createHash('sha256').update(value).digest('hex');
const manifest={schema:1,recipe:recipe.id,recipeSha256:hash(JSON.stringify(recipe)),assetsSha256:hash(JSON.stringify(payload.assets)),runtimeSha256:mediaRuntimeHash(),frameMs,durationMs:playback.duration,outputSha256:hash(fs.readFileSync(output)),stages:payload.queue};
fs.writeFileSync(output.replace('.gif','.json'),JSON.stringify(manifest,null,2)+'\n');
console.log(result.stdout.trim());
