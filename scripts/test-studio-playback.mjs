import assert from 'node:assert/strict';
import {frameAt,frameHold,sequenceCategory,categoryLabel,playbackSelection} from '../frame-studio/dist/playback.js';
const frames=[{durationMs:100},{durationMs:300},{durationMs:50}];
assert.equal(frameAt(frames,99),0);assert.equal(frameAt(frames,100),1);assert.equal(frameAt(frames,400),2);assert.equal(frameAt(frames,450),0);
assert.equal(frameHold(frames[0],{mode:'fixed',fps:12.5,speed:.5}),160);
assert.equal(frameAt(frames,80,{mode:'fixed',fps:12.5}),1);
assert.equal(frameAt(frames,240,{mode:'fixed',fps:12.5}),0);
assert.equal(frameHold(frames[1],{speed:2}),150);assert.equal(frames[1].durationMs,300,'Preview must not change saved timing');
assert.equal(categoryLabel(sequenceCategory({category:'jump',frames})), 'Leaping');
assert.equal(categoryLabel(sequenceCategory({frames:[{metadata:{category:'walk'}}]})),'Walking');
const sequence={frames:[{id:'enter',role:'enter'},{id:'cycle',role:'cycle'},{id:'legacy'},{id:'exit',role:'exit'}]};
const ids=options=>playbackSelection(sequence,options).map(f=>f.id);
assert.deepEqual(ids(),['enter','cycle','legacy','exit']);
assert.deepEqual(ids({includeEnter:false}),['cycle','legacy','exit']);
assert.deepEqual(ids({includeExit:false}),['enter','cycle','legacy']);
assert.deepEqual(ids({includeEnter:false,includeExit:false}),['cycle','legacy']);
assert.deepEqual(playbackSelection({frames:[sequence.frames[0]]},{includeEnter:false}),[]);
assert.equal(sequence.frames.length,4,'Preview filters must not remove saved frames');
console.log('PASS: fractional FPS, speed scaling, saved holds, loop boundaries, categories and independent transition filters.');
